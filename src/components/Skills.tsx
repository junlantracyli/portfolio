const iconColors: Record<string, string> = {
  fastapi: "#009688",
  docker: "#2496ED",
  git: "#F03C2E",
  react: "#61DAFB",
  typescript: "#3178C6",
};

function FolderCard({ folder, delay }: { folder: SkillFolder; delay: number }) {
  const [isHovered, setIsHovered] = useState(false);
  const hasIcons = folder.items.some((item) => "slug" in item && item.slug);

  return (
    <motion.div
      initial={{ opacity: 0, y: 12 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "-40px" }}
      transition={{ duration: 0.4, delay, ease: "easeOut" }}
      onHoverStart={() => setIsHovered(true)}
      onHoverEnd={() => setIsHovered(false)}
      className="relative flex h-96 flex-col items-center justify-end overflow-hidden rounded-2xl border border-white/10 bg-[#0f0f10] p-7 light:border-black/10 light:bg-[#e8e6e1]"
    >
      <div className="relative flex w-64 flex-col items-center">
        {/* Folder back panel: a tall wall items travel up in front of */}
        <div
          style={{ clipPath: folderBackClip }}
          className="absolute inset-x-0 bottom-0 z-0 h-64 w-full bg-[#232326] light:bg-[#d8d6cf]"
        />

        {/* Items start tucked behind the front flap, squished together, and fan out as they rise on hover */}
        <div className="pointer-events-none relative z-[5] h-40 w-full">
          {hasIcons
            ? folder.items.map((item, idx) => {
                const count = folder.items.length;
                const mid = (count - 1) / 2;
                const offset = idx - mid;
                const slug = "slug" in item ? item.slug : undefined;
                const isPython = slug === "python";
                const iconPath = slug ? iconPaths[slug] : undefined;
                const iconColor = slug ? iconColors[slug] : undefined;
                const spreadX = isHovered ? offset * 54 : offset * 10;

                return (
                  <motion.div
                    key={item.title}
                    initial={false}
                    animate={{
                      x: spreadX,
                      y: isHovered ? -48 : 64,
                      rotate: isHovered ? offset * 10 : offset * 3,
                    }}
                    transition={{
                      duration: 0.5,
                      delay: idx * 0.04,
                      ease: "easeOut",
                    }}
                    className="absolute bottom-0 left-1/2 -translate-x-1/2"
                  >
                    {isPython ? (
                      <svg
                        viewBox="0 0 256 254"
                        width="42"
                        height="42"
                        className="drop-shadow-[0_6px_10px_rgba(0,0,0,0.35)]"
                      >
                        {pythonPaths.map((p) => (
                          <path key={p.color} d={p.d} fill={p.color} />
                        ))}
                      </svg>
                    ) : (
                      iconPath && (
                        <svg
                          viewBox="0 0 24 24"
                          width="46"
                          height="46"
                          fill={iconColor}
                          className="drop-shadow-[0_6px_10px_rgba(0,0,0,0.35)]"
                        >
                          <path d={iconPath} />
                        </svg>
                      )
                    )}
                  </motion.div>
                );
              })
            : folder.items.map((item, idx) => {
                const count = folder.items.length;
                const mid = (count - 1) / 2;
                const offset = idx - mid;
                const spreadX = isHovered ? offset * 170 : offset * 8;
                const bullets = "bullets" in item ? item.bullets : undefined;

                return (
                  <motion.div
                    key={item.title}
                    initial={false}
                    animate={{
                      x: spreadX,
                      y: isHovered ? -32 : 112,
                      rotate: isHovered ? offset * 6 : offset * 3,
                    }}
                    transition={{
                      duration: 0.5,
                      delay: idx * 0.04,
                      ease: "easeOut",
                    }}
                    className="absolute bottom-0 left-1/2 h-40 w-52 -translate-x-1/2"
                  >
                    <div
                      style={{ clipPath: paperClip }}
                      className="absolute inset-0 flex flex-col gap-1.5 border border-black/10 bg-[#f5f4f2] px-3 pb-3 pt-4 shadow-[0_10px_20px_rgba(0,0,0,0.35)] light:shadow-[0_10px_20px_rgba(0,0,0,0.15)]"
                    >
                      <p className="pr-3 text-sm font-semibold leading-tight text-black/80">
                        {item.title}
                      </p>
                      {bullets && (
                        <ul className="flex flex-col gap-1 pr-1">
                          {bullets.map((bullet) => (
                            <li
                              key={bullet}
                              className="text-[11px] leading-tight text-black/55"
                            >
                              {bullet}
                            </li>
                          ))}
                        </ul>
                      )}
                    </div>
                  </motion.div>
                );
              })}
        </div>

        {/* Folder front flap */}
        <div
          style={{ clipPath: folderFrontClip }}
          className="relative z-10 h-40 w-full bg-[#1c1c1e] px-7 pb-6 pt-9 light:bg-white"
        >
          <h3 className="text-2xl font-medium">{folder.name}</h3>
          <p className="label mt-1 text-sm text-white/40 light:text-black/40">
            {folder.items.length} Files
          </p>
        </div>
      </div>
    </motion.div>
  );
}

